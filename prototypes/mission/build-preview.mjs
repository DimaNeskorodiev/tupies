import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { Script } from 'node:vm';

const prototypeRoot = new URL('./', import.meta.url);
const repositoryRoot = new URL('../../', import.meta.url);
const cssFiles = [
  '../../public/style.css',
  '../../public/buttons.css',
  '../../public/creature-avatars.css',
  '../../public/mobile.css',
  '../../public/pearl.css',
  'mission.css',
];

function replaceOnce(source, expected, replacement, label) {
  assert.equal(source.split(expected).length - 1, 1, `Expected exactly one ${label}.`);
  return source.replace(expected, () => replacement);
}

function assertEmbeddedCss(css, filename) {
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  assert.doesNotMatch(withoutComments, /@import\b/i, `Unexpected CSS import in ${filename}.`);
  const references = [...withoutComments.matchAll(/url\(\s*(?:"([^"]*)"|'([^']*)'|([^\s)]*))\s*\)/gi)];
  for (const reference of references) {
    const url = reference[1] ?? reference[2] ?? reference[3];
    assert.match(url, /^data:/i, `Non-embedded CSS URL in ${filename}: ${url}`);
  }
  assert.equal(references.length, [...withoutComments.matchAll(/url\(/gi)].length,
    `Unrecognized CSS URL syntax in ${filename}.`);
  assert.doesNotMatch(css, /<\/style\b/i, `Unexpected closing style tag in ${filename}.`);
}

const dataUri = async (path, mime) => `data:${mime};base64,${(await readFile(new URL(path, repositoryRoot))).toString('base64')}`;

const [index, script, cssSources, portraits, brand, favicon] = await Promise.all([
  readFile(new URL('index.html', prototypeRoot), 'utf8'),
  readFile(new URL('mission.js', prototypeRoot), 'utf8'),
  Promise.all(cssFiles.map(async path => ({ path, content: await readFile(new URL(path, prototypeRoot), 'utf8') }))),
  Promise.all(['blue', 'coral', 'jade', 'honey'].map(async variant => [variant,
    await dataUri(`public/assets/companions/companion-${variant}-portrait-128.webp`, 'image/webp'),
  ])),
  dataUri('public/assets/brand/tupies-avatar.webp', 'image/webp'),
  dataUri('public/assets/brand/favicon-64.png', 'image/png'),
]);

let html = index;
for (const { path, content } of cssSources) {
  assertEmbeddedCss(content, path);
  html = replaceOnce(html, `<link rel="stylesheet" href="${path}">`,
    `<style data-source="${path}">\n${content}\n</style>`, `${path} stylesheet link`);
}
html = replaceOnce(html, '../../public/assets/brand/favicon-64.png', favicon, 'favicon URL');

let inlineScript = replaceOnce(script, "  const avatar = (id, size = '', alt = '') =>",
  `  const portablePortraits = Object.freeze(${JSON.stringify(Object.fromEntries(portraits))});\n  const avatar = (id, size = '', alt = '') =>`,
  'avatar declaration');
inlineScript = replaceOnce(inlineScript,
  '../../public/assets/companions/companion-${bots[id].color}-portrait-128.webp',
  '${portablePortraits[bots[id].color]}', 'dynamic avatar URL');
inlineScript = replaceOnce(inlineScript, '../../public/assets/brand/tupies-avatar.webp', brand, 'brand URL');
assert.doesNotMatch(inlineScript, /<\/script\b/i, 'Unexpected closing script tag in prototype script.');
assert.doesNotMatch(inlineScript, /\.\.\/\.\.\/public\//, 'An external prototype asset remains.');
new Script(inlineScript, { filename: 'mission-preview.inline.js' });
html = replaceOnce(html, '<script src="mission.js"></script>', `<script>\n${inlineScript}\n</script>`, 'prototype script');
assert.doesNotMatch(html, /<(?:script|link)\b[^>]*(?:\bsrc|\bhref)\s*=\s*["'](?!data:|#)/i,
  'An external script, stylesheet, or icon dependency remains.');
html = replaceOnce(html, '<!doctype html>', '<!doctype html>\n<!-- Generated by build-preview.mjs. Edit the prototype source files, then rebuild. -->', 'doctype');

await writeFile(new URL('mission-preview.html', prototypeRoot), html);
console.log(`Built mission-preview.html: ${Math.round(Buffer.byteLength(html) / 1024)} KiB, 6 embedded stylesheets, 6 embedded images, no external dependencies.`);
